def make_valid_ogrn(prefix12: str) -> str:
    """Генерирует валидный 13-значный ОГРН с корректной контрольной суммой по модулю 11."""
    assert len(prefix12) == 12 and prefix12.isdigit()
    chk = int(prefix12) % 11 % 10
    return f"{prefix12}{chk}"


