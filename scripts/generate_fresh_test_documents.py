def _create_pdf_with_paragraphs(path: Path, paragraphs: list[str]):
    doc = fitz.open()
    page = doc.new_page(width=595, height=842)  # A4
    font = fitz.Font(fontfile=str(ARIAL_FONT))
    page.insert_font(fontname="f0", fontbuffer=font.buffer)

    y = 50
    for p in paragraphs:
        rect = fitz.Rect(50, y, 545, y + 60)
        # Вставка текста с переносом по строкам
        rc = page.insert_textbox(rect, p, fontname="f0", fontsize=10)
        y += 45
        if y > 780:
            page = doc.new_page(width=595, height=842)
            page.insert_font(fontname="f0", fontbuffer=font.buffer)
            y = 50

    doc.save(str(path))
    doc.close()
    print(f"Created: {path.name}")


