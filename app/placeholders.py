# Типы скобок для плейсхолдеров
BRACKET_TYPES = {
    "square": ("[", "]"),
    "slash": ("/", "/")
}

# Функция для генерации плейсхолдеров с выбранным типом скобок
def generate_placeholders(bracket_type="square", enabled_placeholders=None):
    """Генерирует плейсхолдеры с выбранным типом скобок и активными типами"""
    if enabled_placeholders is None:
        enabled_placeholders = set(PLACEHOLDER_TEMPLATES.keys())

    left_bracket, right_bracket = BRACKET_TYPES.get(bracket_type, ("[", "]"))
    placeholders = {}

    for key, template in PLACEHOLDER_TEMPLATES.items():
        if key in enabled_placeholders:
            placeholders[key] = f"{left_bracket}{template}{right_bracket}"

    return placeholders

