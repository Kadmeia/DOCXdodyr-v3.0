def run_single_mode(
    documents: List[Dict[str, Any]],
    processor: Any,
    enable_pullenti: bool,
    enable_rules: bool,
    enable_ner: bool,
    ner_engine: Optional[LlaimLegalNER] = None,
) -> Dict[str, Any]:
    """Выполняет прогон тестов для одной конфигурации и собирает метрики."""
    pipeline = UnifiedDetectionPipeline(
        enable_pullenti=enable_pullenti,
        enable_rules=enable_rules,
        enable_ner=enable_ner,
        ner_engine=ner_engine,
    )

    total_tp = 0
    total_fp = 0
    total_fn = 0
    by_type: Dict[str, Dict[str, int]] = {}

    fp_list: List[Dict[str, Any]] = []
    fn_list: List[Dict[str, Any]] = []

    doc_times: List[float] = []

    for doc in documents:
        text = doc["text"]
        gt_items = doc["ground_truth"]

        start_t = time.perf_counter()

        pullenti_spans = []
        if enable_pullenti and processor is not None:
            analysis = processor.process(SourceOfAnalysis(text), None, None)
            pullenti_spans = list(iter_pullenti_spans(analysis, text))
            pullenti_spans = list(refine_composite_spans(text, pullenti_spans))

        candidates = pipeline.detect_candidates(text, pullenti_spans)
        elapsed = time.perf_counter() - start_t
        doc_times.append(elapsed)

        # Сопоставление с Ground Truth
        # Считаем True Positive, если вхождение текста GT совпадает с кандидатом
        matched_cands: Set[int] = set()
        matched_gt: Set[int] = set()

        for g_idx, (gt_type, gt_text) in enumerate(gt_items):
            for c_idx, cand in enumerate(candidates):
                if c_idx in matched_cands:
                    continue
                # Сравнение типов с учетом синонимов (RU_ACCOUNT / BANK_ACCOUNT, etc.)
                type_match = (
                    cand.entity_type == gt_type
                    or (cand.entity_type in ("RU_ACCOUNT", "RU_CORR_ACCOUNT") and gt_type == "RU_ACCOUNT")
                    or (cand.entity_type in ("PASSPORT_SERIES", "PASSPORT_NUMBER") and gt_type == "PASSPORT")
                )
                # Текстовое совпадение (полное или подстрочное с высокой точностью)
                c_clean = cand.text.strip(" \t\r\n.,;:()")
                g_clean = gt_text.strip(" \t\r\n.,;:()")
                text_match = (c_clean == g_clean) or (c_clean in g_clean and len(c_clean) >= 4) or (g_clean in c_clean and len(g_clean) >= 4)

                if type_match and text_match:
                    matched_cands.add(c_idx)
                    matched_gt.add(g_idx)
                    total_tp += 1
                    by_type.setdefault(gt_type, {"tp": 0, "fp": 0, "fn": 0})["tp"] += 1
                    break

        # Несопоставленные кандидаты -> False Positives
        for c_idx, cand in enumerate(candidates):
            if c_idx not in matched_cands:
                total_fp += 1
                by_type.setdefault(cand.entity_type, {"tp": 0, "fp": 0, "fn": 0})["fp"] += 1
                fp_list.append({
                    "doc_id": doc["id"],
                    "type": cand.entity_type,
                    "text": cand.text,
                    "source": cand.source,
                })

        # Ненайденные Ground Truth -> False Negatives
        for g_idx, (gt_type, gt_text) in enumerate(gt_items):
            if g_idx not in matched_gt:
                total_fn += 1
                by_type.setdefault(gt_type, {"tp": 0, "fp": 0, "fn": 0})["fn"] += 1
                fn_list.append({
                    "doc_id": doc["id"],
                    "type": gt_type,
                    "text": gt_text,
                })

    precision = total_tp / (total_tp + total_fp) if (total_tp + total_fp) > 0 else 0.0
    recall = total_tp / (total_tp + total_fn) if (total_tp + total_fn) > 0 else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0

    return {
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "tp": total_tp,
        "fp": total_fp,
        "fn": total_fn,
        "by_type": by_type,
        "doc_times": doc_times,
        "mean_doc_time_ms": round(sum(doc_times) / len(doc_times) * 1000, 2),
        "total_time_s": round(sum(doc_times), 3),
        "false_positives": fp_list,
        "false_negatives": fn_list,
    }


